const dictionaries = { en, hi, gu };
let current = en;

export function setLanguage(code) {
  current = dictionaries[code] || en;
}

/** The words for `key` in the chosen language (English when missing), with {name} filled in. */
export function t(key, vars = {}) {
  const text = current[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

